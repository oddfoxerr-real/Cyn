"""Train Cyn's autonomous spectral-role specialist, with disjoint procedural seeds.

Requires NumPy. Input CSVs come from GenerateBalanceData.cpp (shipping analyzer).
No user audio, reference songs, remote inference, or generated music at runtime.
The targets are source energy shares, NOT human judgments of ideal sound.
"""
import argparse
import hashlib
import json
from pathlib import Path
import time
import numpy as np

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--data", type=Path, default=ROOT / "training/generated/balance")
    parser.add_argument("--epochs", type=int, default=300)
    args = parser.parse_args()
    if args.epochs < 1:
        parser.error("--epochs must be positive")
    sets = [np.loadtxt(args.data / f"{name}.csv", delimiter=",") for name in ("train", "validation", "test")]
    if any(d.ndim != 2 or d.shape[1] != 16 or not np.isfinite(d).all() for d in sets):
        raise ValueError("Expected finite 11-feature / 5-label datasets")
    mean = sets[0][:, :11].mean(0)
    std = np.maximum(sets[0][:, :11].std(0), .1)
    xy = [(np.clip((d[:, :11]-mean)/std, -6, 6), d[:, 11:]) for d in sets]
    rng = np.random.default_rng(71291)
    params = [rng.normal(0, .16, (11, 24)), np.zeros(24), rng.normal(0, .16, (24, 5)), np.zeros(5)]
    m = [np.zeros_like(p) for p in params]; v = [p.copy() for p in m]

    def forward(x):
        h = np.tanh(x @ params[0] + params[1])
        z = h @ params[2] + params[3]
        p = np.exp(z-z.max(1, keepdims=True))
        return h, p/p.sum(1, keepdims=True)

    start = time.perf_counter(); step = 0; best = float("inf"); best_epoch = 0
    for epoch in range(args.epochs):
        order = rng.permutation(len(xy[0][0]))
        for begin in range(0, len(order), 128):
            idx = order[begin:begin+128]; x,y = xy[0][0][idx],xy[0][1][idx]
            h,p = forward(x); dz = (p-y)/len(x)
            dh = (dz @ params[2].T)*(1-h*h)
            grads = [x.T @ dh, dh.sum(0), h.T @ dz, dz.sum(0)]
            step += 1
            for i,g in enumerate(grads):
                m[i] = .9*m[i]+.1*g; v[i] = .999*v[i]+.001*g*g
                params[i] -= .002*(m[i]/(1-.9**step))/(np.sqrt(v[i]/(1-.999**step))+1e-8)
        pred = forward(xy[1][0])[1]
        loss = float(np.mean((pred-xy[1][1])**2))
        if loss < best:
            best = loss; best_epoch = epoch+1; saved = [p.copy() for p in params]
        if (epoch+1)%50 == 0:
            print(f"epoch {epoch+1}: validation MSE {loss:.6f}", flush=True)
    params = saved
    pred = forward(xy[2][0])[1]; truth = xy[2][1]
    baseline = np.tile(xy[0][1].mean(0), (len(truth),1))
    mse = float(np.mean((pred-truth)**2)); base_mse = float(np.mean((baseline-truth)**2))
    if mse >= base_mse*.8:
        raise RuntimeError("Model failed held-out improvement gate; no weights exported")
    names = ("bass", "kick", "snare", "high_percussion", "other")
    report = {
        "schema":1, "model":"Cyn Balance 1", "architecture":"11 -> 24 tanh -> 5 softmax",
        "training_rows":len(sets[0]), "validation_rows":len(sets[1]), "test_rows":len(sets[2]),
        "epochs":args.epochs, "selected_epoch":best_epoch, "gradient_updates":step,
        "training_seconds":time.perf_counter()-start,
        "test_mse":mse, "constant_baseline_test_mse":base_mse,
        "test_mae_by_role":dict(zip(names, np.mean(abs(pred-truth),0).tolist())),
        "data_sha256":{n:hashlib.sha256((args.data/f"{n}.csv").read_bytes()).hexdigest() for n in ("train","validation","test")},
        "limitation":"Procedural held-out mixtures only. No real-music, listening-quality, source-separation or perfect-mixing claim. Runtime EQ affects overlapping instruments together."
    }
    header = "// Generated by training/train_balance.py. SPDX-License-Identifier: AGPL-3.0-or-later\n#pragma once\nnamespace CynBalanceWeights {\n"
    for name,arr in zip(("mean","scale","w1","b1","w2","b2"), (mean,std,*params)):
        values = ",".join(f"{float(x):.9e}f" for x in arr.flat)
        header += f"inline constexpr float {name}[{arr.size}] = {{{values}}};\n"
    header += "}\n"
    target = ROOT / "fxsound/Source/GUI/CynBalanceWeights.h"
    target.write_text(header)
    report["weights_sha256"] = hashlib.sha256(target.read_bytes()).hexdigest()
    (ROOT / "models/balance-evaluation.json").write_text(json.dumps(report, indent=2)+"\n")
    # Native parity cases use unseen test inputs, not training rows.
    fixture = ROOT / "tests/data/balance-parity.csv"
    fixture.parent.mkdir(exist_ok=True)
    np.savetxt(fixture, np.c_[sets[2][:64,:11],pred[:64]], delimiter=",", fmt="%.9g")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    main()

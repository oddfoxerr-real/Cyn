import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const read=p=>readFileSync(new URL("../"+p,import.meta.url),"utf8");
const installer=read("Installer/Cyn/Cyn.iss");
const native=read("riff-cyn/native-bridge.cjs");
const main=read("riff-cyn/main.cjs");
const preload=read("riff-cyn/preload.cjs");
const settings=read("riff-cyn/renderer/settings.js");
const release=read(".github/workflows/windows-release.yml");
const guiWorkflow=read(".github/workflows/cyn-riff-native-shell.yml");
const notes=read("RELEASE_NOTES_2.0.85.md");
assert.match(installer,/^AppVersion=2\.0\.84$/m);
assert.match(installer,/^AppId=\{\{3049F105-E971-49A1-876E-50FDB14EF351\}$/m);
assert(installer.includes('Source: "{#PayloadDir}\\*"'),"Keep the native driver, assets and Material interface together");
assert(installer.includes('Filename: "{app}\\CYN-Interface\\CYN Audio.exe"'),"Default CYN launcher must open the Material shell");
assert(installer.includes('Name: "{autoprograms}\\Cyn (Classic)"'),"Keep the full native AI/driver troubleshooting UI available");
assert(installer.includes('Name="CYN Audio.exe"'),"Updates must not overwrite an actively running Electron frontend");
assert(native.includes('path.dirname(process.execPath),"..","Cyn.exe"'),"Locate the native audio processor beside the bundled shell");
assert(main.includes('bridge.launch().catch'),"Integrated CYN must initialize the native audio engine");
assert(main.includes('ipcMain.handle("cyn:check-updates"'),"Material CYN needs the actual Windows updater");
assert(main.includes('"CynUpdater.ps1"'),"Invoke the existing secure SHA-256 updater");
assert(main.includes('"-CurrentVersion",version[1],"-Interactive"'),
  "Updater requires the installed native version and an interactive window");
assert(main.includes('live.status.version'),
  "Pass the actual native CYN version instead of Electron shell version");
assert(preload.includes('checkUpdates:()=>ipcRenderer.invoke("cyn:check-updates")'));
assert(settings.includes('updates:()=>window.cyn.checkUpdates()'));
assert(release.includes("npx electron-builder --win --x64 --dir"),"Build the Electron frontend, not the separate NSIS installer");
assert(release.includes("dist/Cyn/CYN-Interface"),"Stage the frontend in the native Inno payload");
assert(release.includes("Compress-Archive -Path 'dist/Cyn/*'"),"Rebuild the portable archive with frontend included");
assert(release.includes("Node".toLowerCase())||release.includes("setup-node@v4"));
assert(notes.includes("normal CYN Windows installer"));
assert(!guiWorkflow.includes("AppId={{3049F105-E971-49A1-876E-50FDB14EF351}"),"Standalone preview must not replace native AppId");
console.log("PASS: one CYN 2.0.85 update channel, retained FxSound native audio, and bundled Material frontend");

import {readFileSync} from "node:fs";
import assert from "node:assert/strict";
const path=p=>new URL("../"+p,import.meta.url);
const src=readFileSync(path("dsp/include/SourceAudioAnalyzer.h"),"utf8");
const worker=readFileSync(path("fxsound/Source/GUI/CynYamNetWorker.h"),"utf8");
const controller=readFileSync(path("fxsound/Source/GUI/FxController.cpp"),"utf8");
const model=readFileSync(path("experiments/yamnet/convert_and_verify.py"),"utf8");
assert(src.includes("feedYamNet((float)(monoSum/channels_))"),"No real input waveform tap");
assert(src.includes("std::array<std::atomic<float>,yamnetRingCapacity>"),"Waveform ring must be race-safe");
assert(src.includes("std::memory_order_release"),"Producer must publish atomically");
assert(worker.includes("juce::Thread")&&worker.includes("stopThread(15000)"),"Inference needs isolated worker");
assert(worker.includes("api->Run(session")&&worker.includes("api->CreateSession("),"Worker must actually execute pretrained ONNX model");
assert(worker.includes("scores[0]")&&worker.includes("scores[132]")&&worker.includes("scores[420]"),"Must classify actual YAMNet labels");
assert(worker.includes("source_.copyYamNetWindow"),"Worker must use bounded waveform tap");
assert(controller.includes("yamnet_worker_->startIfAvailable()"),"Live YAMNet never starts");
assert(controller.includes("yamnet_worker_->latest("), "Predictions must inform DSP");
assert(controller.includes("if(yamnetLive && movie && e==0)")&&controller.includes("if(yamnetLive && movie && e==4)"),"Movie AI not YAMNet aware");
assert(model.includes("onnxruntime"),"Missing tested pretrained model conversion");
console.log("PASS: native YAMNet audio tap, ONNX inference and limited-bass control");
